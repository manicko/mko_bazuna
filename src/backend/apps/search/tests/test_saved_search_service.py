class TestBoundQuery:
    def test_at_cap_round_trips_byte_identical(self) -> None:
        at_cap = "a" * QUERY_MAX_LENGTH
        assert bound_query(at_cap) == at_cap

    def test_one_over_cap_raises_with_length(self) -> None:
        over = "a" * (QUERY_MAX_LENGTH + 1)
        with pytest.raises(QueryTooLongError) as excinfo:
            bound_query(over)
        assert excinfo.value.length == QUERY_MAX_LENGTH + 1

    def test_redaction_never_lengthens(self) -> None:
        raw = ("+381641234567 " + "b" * 100).ljust(QUERY_MAX_LENGTH, "b")[:QUERY_MAX_LENGTH]
        assert len(bound_query(raw)) <= len(raw)

    def test_strips_surrounding_whitespace(self) -> None:
        assert bound_query("  велосипед  ") == "велосипед"


