class TestToggle:
    def test_toggle_flips_active_and_keeps_row(self, buyer: User) -> None:
        ss = SavedSearch.objects.create(user=buyer, is_active=True)

        result = toggle_saved_search(buyer, ss.pk)
        assert result.is_active is False
        assert SavedSearch.objects.get(pk=ss.pk).is_active is False
        assert SavedSearch.objects.filter(user=buyer).count() == 1

        toggle_saved_search(buyer, ss.pk)
        assert SavedSearch.objects.get(pk=ss.pk).is_active is True

    def test_toggle_foreign_row_raises_does_not_exist(self, buyer: User) -> None:
        other = make_user(940000402)
        ss = SavedSearch.objects.create(user=other, is_active=True)

        with pytest.raises(SavedSearch.DoesNotExist):
            toggle_saved_search(buyer, ss.pk)

        assert SavedSearch.objects.get(pk=ss.pk).is_active is True


