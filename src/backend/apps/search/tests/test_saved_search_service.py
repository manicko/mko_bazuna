class TestUpdate:
    def test_update_persists_query_and_filters(self, buyer: User, category: Category, city: City) -> None:
        ss = SavedSearch.objects.create(user=buyer, query="старое", min_price=1)

        update_saved_search(
            buyer,
            ss.pk,
            query="самокат",
            filters=_filters(
                city_id=city.id,
                category_id=category.id,
                min_price=10,
                max_price=200,
            ),
            language=_EN,
        )

        refreshed = SavedSearch.objects.get(pk=ss.pk)
        assert refreshed.query == "самокат"
        assert refreshed.city_id == city.id
        assert refreshed.category_id == category.id
        assert refreshed.min_price == 10
        assert refreshed.max_price == 200
        assert refreshed.language == _EN

    def test_update_blank_query_stored_as_none(self, buyer: User) -> None:
        ss = SavedSearch.objects.create(user=buyer, query="старое")
        update_saved_search(buyer, ss.pk, query="   ", filters=_filters(), language=_EN)
        assert SavedSearch.objects.get(pk=ss.pk).query is None

    def test_update_falsy_language_keeps_stored_language(self, buyer: User) -> None:
        ss = SavedSearch.objects.create(user=buyer, query="q", language="ru")
        update_saved_search(buyer, ss.pk, query="q2", filters=_filters(), language="")
        assert SavedSearch.objects.get(pk=ss.pk).language == "ru"

    def test_update_clears_city_and_category_when_unset(self, buyer: User, category: Category, city: City) -> None:
        ss = SavedSearch.objects.create(user=buyer, city=city, category=category)
        update_saved_search(buyer, ss.pk, query="q", filters=_filters(), language=_EN)
        refreshed = SavedSearch.objects.get(pk=ss.pk)
        assert refreshed.city_id is None
        assert refreshed.category_id is None

    def test_update_foreign_row_raises_does_not_exist(self, buyer: User) -> None:
        other = make_user(940000401)
        ss = SavedSearch.objects.create(user=other, query="чужой")

        with pytest.raises(SavedSearch.DoesNotExist):
            update_saved_search(buyer, ss.pk, query="mine", filters=_filters(), language=_EN)

        # Untouched.
        assert SavedSearch.objects.get(pk=ss.pk).query == "чужой"


