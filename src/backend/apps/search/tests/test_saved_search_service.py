"""
Service-tier tests for the saved-search mutator service.

These pin the extracted ``apps.search.services.saved_searches`` contract that
the HTML callers (the create modal and the cabinet management views) share.
They exercise the service directly (no HTTP), so they prove the shared stack
that the untouched HTML-flow suites (``test_saved_search_create.py``,
``test_cabinet_sections.py``, ``test_saved_search_input_boundary.py``) already
cover end-to-end is the *same* behavior:

- **CRUD correctness** — create/update/toggle/delete persist exactly the fields
  the HTML callers persisted, with the ``SavedSearchInput`` DTO as shared state.
- **Ownership** — every row-scoped operation refuses another user's row with
  ``SavedSearch.DoesNotExist`` (the exception the HTML views map to ``Http404``).
- **Token behavior** — the ``unsubscribe_token`` is generated on create and is
  never regenerated by update, toggle or delete.
- **Query bound** — ``bound_query`` redacts then refuses an over-cap value.

Deliberately NOT duplicated here: the rendered fragments / 400 / 302 shapes
(the HTML-flow suites own those).
"""

from __future__ import annotations

import pytest

from apps.categories.models import Category
from apps.locations.models import City
from apps.search.models import SavedSearch
from apps.search.schemas import SavedSearchInput
from apps.search.services.saved_searches import (
    QUERY_MAX_LENGTH,
    QueryTooLongError,
    bound_query,
    create_saved_search,
    delete_saved_search,
    toggle_saved_search,
    update_saved_search,
)
from apps.users.models import User
from conftest import make_user

pytestmark = [pytest.mark.django_db, pytest.mark.integration]

# Locale used by the HTML callers in the test environment.
_EN = "en"


def _filters(**kwargs: object) -> SavedSearchInput:
    """Build the shared filters DTO (extra keys are rejected by the DTO)."""
    return SavedSearchInput(**kwargs)


# ---------------------------------------------------------------------------
# create
# ---------------------------------------------------------------------------


class TestCreate:
    def test_create_persists_fields_and_defaults(self, buyer: User, category: Category, city: City) -> None:
        ss = create_saved_search(
            buyer,
            query="велосипед",
            filters=_filters(
                city_id=city.id,
                category_id=category.id,
                min_price=100,
                max_price=500,
            ),
            language=_EN,
        )

        persisted = SavedSearch.objects.get(pk=ss.pk)
        assert persisted.user_id == buyer.id
        assert persisted.query == "велосипед"
        assert persisted.city_id == city.id
        assert persisted.category_id == category.id
        assert persisted.min_price == 100
        assert persisted.max_price == 500
        assert persisted.is_active is True
        assert persisted.language == _EN

    def test_create_blank_query_stored_as_none(self, buyer: User) -> None:
        ss = create_saved_search(buyer, query="", filters=_filters(), language=_EN)
        assert SavedSearch.objects.get(pk=ss.pk).query is None

    def test_create_falls_back_to_bosnian_when_language_falsy(self, buyer: User) -> None:
        """A falsy locale uses the model default ('' -> LanguageLocale.BOSNIAN)."""
        ss = create_saved_search(buyer, query="q", filters=_filters(), language="")
        assert SavedSearch.objects.get(pk=ss.pk).language == "bs"

    def test_create_redacts_pii(self, buyer: User) -> None:
        ss = create_saved_search(
            buyer,
            query="Ivan Petrov +381641234567 ivan.petrov@example.com",
            filters=_filters(),
            language=_EN,
        )
        stored = SavedSearch.objects.get(pk=ss.pk).query or ""
        assert "381641234567" not in stored
        assert "ivan.petrov@example.com" not in stored
        assert "Ivan Petrov" not in stored

    def test_create_validates_filters_shared_dto(self, buyer: User) -> None:
        """A negative price is refused by the shared DTO, nothing is stored."""
        from pydantic import ValidationError

        with pytest.raises(ValidationError):
            _filters(min_price=-1)
        assert not SavedSearch.objects.filter(user=buyer).exists()


