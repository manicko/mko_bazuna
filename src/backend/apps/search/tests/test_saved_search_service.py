class TestUnsubscribeToken:
    def test_token_generated_on_create(self, buyer: User) -> None:
        ss = create_saved_search(buyer, query="q", filters=_filters(), language=_EN)
        assert ss.unsubscribe_token
        assert len(ss.unsubscribe_token) == 32

    def test_update_does_not_regenerate_token(
        self, buyer: User, category: Category, city: City
    ) -> None:
        ss = SavedSearch.objects.create(user=buyer, query="q")
        before = ss.unsubscribe_token

        update_saved_search(
            buyer,
            ss.pk,
            query="new",
            filters=_filters(category_id=category.id, city_id=city.id, min_price=5),
            language=_EN,
        )

        assert SavedSearch.objects.get(pk=ss.pk).unsubscribe_token == before

    def test_toggle_does_not_regenerate_token(self, buyer: User) -> None:
        ss = SavedSearch.objects.create(user=buyer)
        before = ss.unsubscribe_token

        toggle_saved_search(buyer, ss.pk)

        assert SavedSearch.objects.get(pk=ss.pk).unsubscribe_token == before

    def test_token_stable_across_create_then_toggle(self, buyer: User) -> None:
        ss = create_saved_search(buyer, query="q", filters=_filters(), language=_EN)
        token = ss.unsubscribe_token
        toggle_saved_search(buyer, ss.pk)
        assert SavedSearch.objects.get(pk=ss.pk).unsubscribe_token == token

    def test_tokens_are_unique_across_rows(self, buyer: User) -> None:
        a = create_saved_search(buyer, query="a", filters=_filters(), language=_EN)
        b = create_saved_search(buyer, query="b", filters=_filters(), language=_EN)
        assert a.unsubscribe_token != b.unsubscribe_token
